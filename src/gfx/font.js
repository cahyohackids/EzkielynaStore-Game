export const GLYPH_W = 5, GLYPH_H = 7, ADV = 6;
const cache = new Map();

function atlas(color) {
  let a = cache.get(color);
  if (a) return a;
  const keys = Object.keys(G);
  const c = document.createElement('canvas');
  c.width = keys.length * ADV;
  c.height = GLYPH_H;
  const ctx = c.getContext('2d');
  ctx.fillStyle = color;
  const map = {};
  keys.forEach((k, i) => {
    map[k] = i * ADV;
    const bits = G[k];
    for (let j = 0; j < 35; j++) if (bits[j] === '1') ctx.fillRect(i * ADV + (j % 5), (j / 5) | 0, 1, 1);
  });
  a = { c, map };
  cache.set(color, a);
  return a;
}

export function textWidth(s, scale = 1) { return (s.length * ADV - 1) * scale; }

/**
 * Draw text. align: 'left' | 'center' | 'right'. shadow: colour drawn 1px below.
 */
export function drawText(ctx, str, x, y, color, { scale = 1, align = 'left', shadow = null } = {}) {
  const s = String(str).toUpperCase().replace(/×/g, 'x');
  const w = textWidth(s, scale);
  let ox = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  y = Math.round(y);
  if (shadow) drawText(ctx, str, ox, y + scale, shadow, { scale });
  const a = atlas(color);
  for (let i = 0; i < s.length; i++) {
    const ch = s[i] === 'X' && str[i] === 'x' ? 'x' : s[i];
    const sx = a.map[ch] ?? a.map[' '];
    ctx.drawImage(a.c, sx, 0, GLYPH_W, GLYPH_H, ox + i * ADV * scale, y, GLYPH_W * scale, GLYPH_H * scale);
  }
}
